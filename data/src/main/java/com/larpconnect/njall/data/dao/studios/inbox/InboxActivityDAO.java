package com.larpconnect.njall.data.dao.studios.inbox;

import com.google.common.collect.ImmutableList;
import com.google.common.collect.ImmutableMap;
import com.google.common.collect.ImmutableSet;
import com.google.common.collect.ImmutableSetMultimap;
import com.larpconnect.njall.data.domain.inbox.InboxActivityRecord;
import java.time.Instant;
import java.util.Set;
import java.util.UUID;

/** DAO interface for activity deduplication and pre-queue generator recipient routing. */
public interface InboxActivityDAO {

  /**
   * Resolves which candidate recipient identifiers are active and transitively generated by the
   * receiving actor in the studio tenant.
   *
   * @param tenantId Studio tenant UUID.
   * @param receivingActorId The receiving actor UUID targeted by the request path.
   * @param candidateIdentifiers Set of recipient identifiers (UUIDs or preferred usernames).
   * @return Immutable set of verified active descendant Actor UUIDs.
   */
  ImmutableSet<UUID> resolveRoutableRecipients(
      UUID tenantId, UUID receivingActorId, Set<String> candidateIdentifiers);

  /**
   * Resolves candidate recipient identifiers in bulk and returns a lowercase identifier-to-UUID
   * lookup map (mapping both lowercase actor UUID strings and lowercase preferred usernames to
   * verified descendant Actor UUIDs).
   *
   * @param tenantId Studio tenant UUID.
   * @param receivingActorId The receiving actor UUID targeted by the request path.
   * @param candidateIdentifiers Union of recipient identifiers across a batch.
   * @return Immutable map from lowercase candidate identifier to verified Actor UUID.
   */
  ImmutableMap<String, UUID> resolveRoutableRecipientMap(
      UUID tenantId, UUID receivingActorId, Set<String> candidateIdentifiers);

  /**
   * Filters the given target actor IDs to return only those for which no unexpired deduplication
   * record exists for the given activity ID.
   *
   * @param tenantId Studio tenant UUID.
   * @param activityId The unique activity URI / ID.
   * @param targetActorIds Set of candidate target actor UUIDs.
   * @param now Current timestamp for checking expiration.
   * @return Subset of target actor UUIDs that have not yet processed this activity within 8 days.
   */
  ImmutableSet<UUID> filterUnseenTargets(
      UUID tenantId, String activityId, Set<UUID> targetActorIds, Instant now);

  /**
   * Filters candidate {@code (activityId, targetActorId)} pairs across a batch in a single database
   * round-trip, returning only pairs with no unexpired deduplication record.
   *
   * @param tenantId Studio tenant UUID.
   * @param activityTargets Multimap of activity IDs to candidate target actor UUIDs.
   * @param now Current timestamp for checking expiration.
   * @return Multimap of unseen {@code (activityId, targetActorId)} pairs.
   */
  ImmutableSetMultimap<String, UUID> filterUnseenTargetsBatch(
      UUID tenantId, ImmutableSetMultimap<String, UUID> activityTargets, Instant now);

  /**
   * Persists deduplication records for accepted target actors into the database.
   *
   * @param tenantId Studio tenant UUID.
   * @param activityId The unique activity URI / ID.
   * @param targetActorIds Set of recipient actor UUIDs that accepted the activity.
   * @param receivedOn Timestamp when the activity was accepted.
   * @param expiresOn Timestamp when the deduplication records should expire.
   */
  void recordAcceptedActivity(
      UUID tenantId,
      String activityId,
      Set<UUID> targetActorIds,
      Instant receivedOn,
      Instant expiresOn);

  /**
   * Persists deduplication records for multiple accepted activities in a single transaction using
   * canonical primary-key lock ordering.
   *
   * @param tenantId Studio tenant UUID.
   * @param records Immutable list of accepted activity deduplication records.
   */
  void recordAcceptedActivities(UUID tenantId, ImmutableList<InboxActivityRecord> records);
}
