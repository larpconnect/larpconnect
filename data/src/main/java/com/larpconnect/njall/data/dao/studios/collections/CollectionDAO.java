package com.larpconnect.njall.data.dao.studios.collections;

import com.google.common.collect.ImmutableList;
import com.larpconnect.njall.data.domain.Collection;
import com.larpconnect.njall.data.domain.ExpandedEntity;
import java.util.Optional;
import java.util.UUID;

/** DAO interface for tenanted studio collections and collection items. */
public interface CollectionDAO {

  /**
   * Checks whether {@code actorId} references an active Actor entity in {@code tenantId}.
   *
   * @param tenantId Studio tenant UUID.
   * @param actorId Actor entity UUID.
   * @return True if the entity exists, is not soft-deleted, and has type {@code Actor}.
   */
  boolean isActiveActor(UUID tenantId, UUID actorId);

  /**
   * Retrieves a collection by tenant, generating actor, and ID, including ordered active item IDs.
   *
   * @param tenantId Studio tenant UUID.
   * @param actorId Generating actor UUID.
   * @param collectionId Collection UUID.
   * @return Optional containing the collection if found, active, and generated by {@code actorId}.
   */
  Optional<Collection> findById(UUID tenantId, UUID actorId, UUID collectionId);

  /**
   * Retrieves active items in a collection generated by {@code actorId}, expanded as entities with
   * names/summaries.
   *
   * @param tenantId Studio tenant UUID.
   * @param actorId Generating actor UUID.
   * @param collectionId Collection UUID.
   * @return Ordered list of expanded entities, or empty if actor/collection is missing or
   *     mismatched.
   */
  ImmutableList<ExpandedEntity> findExpandedItems(UUID tenantId, UUID actorId, UUID collectionId);

  /**
   * Checks if an active collection exists for the given owner and name.
   *
   * @param tenantId Studio tenant UUID.
   * @param ownerId Owner entity UUID.
   * @param name Collection name.
   * @param excludeId Optional collection ID to exclude (for PATCH).
   * @return True if another collection already exists with that owner and name.
   */
  boolean existsByOwnerAndName(UUID tenantId, UUID ownerId, String name, Optional<UUID> excludeId);

  /**
   * Creates a new collection under the specified studio tenant.
   *
   * @param tenantId Studio tenant UUID.
   * @param generator Generating actor entity UUID.
   * @param ownerId Semantic owner entity UUID.
   * @param name Collection name.
   * @param summary Optional description summary.
   * @return Created collection.
   */
  Collection create(
      UUID tenantId, UUID generator, UUID ownerId, String name, Optional<String> summary);

  /**
   * Applies partial updates to a collection generated by {@code actorId}.
   *
   * @param tenantId Studio tenant UUID.
   * @param actorId Generating actor UUID.
   * @param collectionId Collection UUID.
   * @param name Optional new collection name.
   * @param summary Optional new summary.
   * @return Optional containing the updated collection if found, active, and generated by {@code
   *     actorId}.
   */
  Optional<Collection> patch(
      UUID tenantId,
      UUID actorId,
      UUID collectionId,
      Optional<String> name,
      Optional<String> summary);

  /**
   * Soft-deletes a collection generated by {@code actorId}.
   *
   * @param tenantId Studio tenant UUID.
   * @param actorId Generating actor UUID.
   * @param collectionId Collection UUID.
   * @return True if collection was active, generated by {@code actorId}, and soft-deleted; false
   *     otherwise.
   */
  boolean softDelete(UUID tenantId, UUID actorId, UUID collectionId);

  /**
   * Adds an entity reference to a collection generated by {@code actorId}, optionally before
   * another item or at an index.
   *
   * @param tenantId Studio tenant UUID.
   * @param actorId Generating actor UUID.
   * @param collectionId Collection UUID.
   * @param refersToId Referenced entity UUID.
   * @param before Optional entity UUID before which to insert.
   * @param index Optional zero-based index for insertion.
   * @return True if successfully added or already present (idempotent), false if actor, collection,
   *     or referenced entity is not found or mismatched.
   */
  boolean addItem(
      UUID tenantId,
      UUID actorId,
      UUID collectionId,
      UUID refersToId,
      Optional<UUID> before,
      Optional<Integer> index);

  /**
   * Removes an entity reference from a collection generated by {@code actorId}.
   *
   * @param tenantId Studio tenant UUID.
   * @param actorId Generating actor UUID.
   * @param collectionId Collection UUID.
   * @param refersToId Referenced entity UUID to remove.
   * @return True if successfully removed or idempotent, false if actor or collection is not found
   *     or mismatched.
   */
  boolean removeItem(UUID tenantId, UUID actorId, UUID collectionId, UUID refersToId);
}
