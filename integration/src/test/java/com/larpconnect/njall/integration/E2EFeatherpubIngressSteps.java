  @Then(
      "the published message on queue {string} at index {int} has fresh server traceparent"
          + " matching response and distinct from {string}")
  public void thePublishedMessageHasFreshServerTraceparent(
      String queue, int index, String untrustedTraceparent) {
    var responseTraceparent = requireResponse().headers().firstValue("traceparent").orElse("");
    assertThat(responseTraceparent)
        .matches("^00-(?!0{32})[0-9a-f]{32}-(?!0{16})[0-9a-f]{16}-[0-9a-f]{2}$")
        .isNotEqualTo(resolveVariables(untrustedTraceparent));
    E2EFeatherpubAmqpFixture.assertTraceparent(index, responseTraceparent);
  }

