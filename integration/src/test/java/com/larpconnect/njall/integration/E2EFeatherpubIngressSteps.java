  // --- Helper Methods ---

  private UUID resolveTenantId(String studioAlias) {
    var id = rememberedIds.get(studioAlias + "_tenant_id");
    return id != null ? UUID.fromString(id) : UUID.randomUUID();
  }

  private UUID resolveActorUuid(String actorRef) {
    var resolved = resolveVariables(actorRef);
    var rem = rememberedIds.get(resolved + "_id");
    if (rem != null) return UUID.fromString(rem);
    try {
      return UUID.fromString(resolved);
    } catch (IllegalArgumentException e) {
      return UUID.nameUUIDFromBytes(resolved.getBytes(StandardCharsets.UTF_8));
    }
  }

  private String resolveVariables(String input) {
    var res = E2EFeatherpubAmqpFixture.substituteTimestamps(input);
    for (var e : rememberedIds.entrySet()) res = res.replace("{" + e.getKey() + "}", e.getValue());
    return res;
  }
