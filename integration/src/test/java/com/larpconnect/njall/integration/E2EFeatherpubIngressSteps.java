  // --- Category D: HTTP Response & Batch Failure Assertions ---

  private HttpResponse<String> requireResponse() {
    var resp = fixture.getLastResponse();
    assertThat(resp).isNotNull();
    return resp;
  }

  private JsonNode requireRootJson() {
    var root = fixture.getRootJson();
    assertThat(root).isNotNull();
    return root;
  }

  @Then("the ingress response status code should be {int}")
  public void theIngressResponseStatusCodeShouldBe(int expectedStatus) {
    assertThat(requireResponse().statusCode()).isEqualTo(expectedStatus);
  }

  @Then("the ingress response body should be empty")
  public void theIngressResponseBodyShouldBeEmpty() {
    assertThat(requireResponse().body()).isBlank();
  }

  @Then("the ingress response content-type should contain {string}")
  public void theIngressResponseContentTypeShouldContain(String expectedType) {
    assertThat(requireResponse().headers().firstValue("Content-Type").orElse(""))
        .contains(expectedType);
  }

  @Then("the ingress response JSON contains field {string} with value {string}")
  public void theIngressResponseJsonContainsFieldWithValue(String field, String expectedVal) {
    assertThat(requireRootJson().path(field).asText()).isEqualTo(resolveVariables(expectedVal));
  }

  @Then("the ingress response error has code {int} and non-empty message")
  public void theIngressResponseErrorHasCodeAndNonEmptyMessage(int expectedCode) {
    var root = requireRootJson();
    assertThat(root.path("code").asInt()).isEqualTo(expectedCode);
    assertThat(root.path("message").asText()).isNotBlank();
  }

  @Then("the ingress batch response has no failed requests")
  public void theIngressBatchResponseHasNoFailedRequests() {
    var failed = requireRootJson().path("failedRequests");
    assertThat(failed.isMissingNode() || failed.isNull() || failed.isEmpty())
        .as("Batch response failedRequests should be empty")
        .isTrue();
  }

  @Then(
      "the ingress batch response contains failed request at index {string} with code {int} and"
          + " non-empty message")
  public void theIngressBatchResponseContainsFailedRequest(String index, int code) {
    var failed = requireRootJson().path("failedRequests").path(index);
    assertThat(failed.isMissingNode()).isFalse();
    assertThat(failed.path("code").asInt()).isEqualTo(code);
    assertThat(failed.path("message").asText()).isNotBlank();
  }

  @Then("the ingress batch response does not contain failed request at index {string}")
  public void theIngressBatchResponseDoesNotContainFailedRequest(String index) {
    assertThat(requireRootJson().path("failedRequests").has(index)).isFalse();
  }

  @Then("the ingress batch response failed requests count is {int}")
  public void theIngressBatchResponseFailedRequestsCountIs(int expectedCount) {
    assertThat(requireRootJson().path("failedRequests").size()).isEqualTo(expectedCount);
  }

  @Then("the ingress response field {string} is remembered as {string}")
  public void theIngressResponseFieldIsRememberedAs(String field, String rememberKey) {
    rememberedIds.put(rememberKey, requireRootJson().path(field).asText());
  }

  @Then("the ingress response JSON array {string} has length {int}")
  public void theIngressResponseJsonArrayHasLength(String field, int expectedLen) {
    assertThat(requireRootJson().path(field).size()).isEqualTo(expectedLen);
  }

